/// Convierte datos de ruta SVG (`d`) en un [Path]. Solo soporta lo que exporta Figma para estos íconos:
/// M, L, H, V, C, S, Q y Z (absolutos y relativos). Cualquier otra instrucción lanza [FormatException].
Path parseSvgPath(String d) {
  final tokens = RegExp(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?').allMatches(d).map((m) => m[0]!).toList();
  final path = Path();
  var i = 0;
  var cmd = '';
  var x = 0.0, y = 0.0; // punto actual
  var startX = 0.0, startY = 0.0; // inicio del subtrazado, para Z
  var ctrlX = 0.0, ctrlY = 0.0; // último punto de control, para S

  bool isCommand(String t) => RegExp(r'[A-Za-z]').hasMatch(t);
  double next() => double.parse(tokens[i++]);

  while (i < tokens.length) {
    if (isCommand(tokens[i])) {
      cmd = tokens[i++];
      if (cmd == 'Z' || cmd == 'z') {
        path.close();
        x = startX;
        y = startY;
        continue;
      }
    } else if (cmd.isEmpty || cmd == 'Z' || cmd == 'z') {
      throw FormatException('Ruta SVG inválida cerca del token ${tokens[i]}', d);
    }

    final rel = cmd == cmd.toLowerCase();
    switch (cmd.toUpperCase()) {
      case 'M':
        final nx = next() + (rel ? x : 0), ny = next() + (rel ? y : 0);
        path.moveTo(nx, ny);
        x = startX = nx;
        y = startY = ny;
        cmd = rel ? 'l' : 'L'; // los pares siguientes de un M son L implícitos
      case 'L':
        final nx = next() + (rel ? x : 0), ny = next() + (rel ? y : 0);
        path.lineTo(nx, ny);
        x = nx;
        y = ny;
      case 'H':
        x = next() + (rel ? x : 0);
        path.lineTo(x, y);
      case 'V':
        y = next() + (rel ? y : 0);
        path.lineTo(x, y);
      case 'C':
        final x1 = next() + (rel ? x : 0), y1 = next() + (rel ? y : 0);
        final x2 = next() + (rel ? x : 0), y2 = next() + (rel ? y : 0);
        final nx = next() + (rel ? x : 0), ny = next() + (rel ? y : 0);
        path.cubicTo(x1, y1, x2, y2, nx, ny);
        ctrlX = x2;
        ctrlY = y2;
        x = nx;
        y = ny;
      case 'S':
        final x1 = 2 * x - ctrlX, y1 = 2 * y - ctrlY;
        final x2 = next() + (rel ? x : 0), y2 = next() + (rel ? y : 0);
        final nx = next() + (rel ? x : 0), ny = next() + (rel ? y : 0);
        path.cubicTo(x1, y1, x2, y2, nx, ny);
        ctrlX = x2;
        ctrlY = y2;
        x = nx;
        y = ny;
      case 'Q':
        final x1 = next() + (rel ? x : 0), y1 = next() + (rel ? y : 0);
        final nx = next() + (rel ? x : 0), ny = next() + (rel ? y : 0);
        path.quadraticBezierTo(x1, y1, nx, ny);
        x = nx;
        y = ny;
      default:
        throw FormatException('Instrucción SVG no soportada: $cmd', d);
    }
  }
  return path;
}

class _IconPart {
  _IconPart.fill(String d, this.color)
      : path = parseSvgPath(d),
        strokeWidth = null;

  _IconPart.stroke(String d, this.color, double width)
      : path = parseSvgPath(d),
        strokeWidth = width;

  final Path path;
  final Color color;
  final double? strokeWidth; // null = relleno
}


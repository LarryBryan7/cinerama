/// Dibuja un [FigmaIconData] en su tamaño nativo. Con [tint] reemplaza el color del ícono (por ejemplo, la pestaña activa).
class FigmaIcon extends StatelessWidget {
  const FigmaIcon(this.data, {super.key, this.tint});

  final FigmaIconData data;
  final Color? tint;

  @override
  Widget build(BuildContext context) => ExcludeSemantics(
        child: SizedBox(
          width: data.width,
          height: data.height,
          child: CustomPaint(painter: _FigmaIconPainter(data, tint)),
        ),
      );
}

class _FigmaIconPainter extends CustomPainter {
  const _FigmaIconPainter(this.data, this.tint);

  final FigmaIconData data;
  final Color? tint;

  @override
  void paint(Canvas canvas, Size size) {
    for (final part in data._parts) {
      final paint = Paint()
        ..isAntiAlias = true
        ..color = tint ?? part.color;
      final width = part.strokeWidth;
      if (width != null) {
        paint
          ..style = PaintingStyle.stroke
          ..strokeWidth = width
          ..strokeCap = StrokeCap.round
          ..strokeJoin = StrokeJoin.round;
      }
      canvas.drawPath(part.path, paint);
    }
  }

  @override
  bool shouldRepaint(_FigmaIconPainter oldDelegate) => oldDelegate.data != data || oldDelegate.tint != tint;
}
